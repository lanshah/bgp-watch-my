"""Build the watch list from live sources, with provenance.

For every candidate ASN in the config:
  1. RIPEstat as-overview      -> registered holder name, whether it is announced
  2. RIPEstat country-resource-list?resource=MY -> is the ASN registered to Malaysia?
  3. PeeringDB /net?asn=       -> operator's self-declared network name (if listed)
An ASN is accepted only if it is registered to MY *and* its holder (or PeeringDB name)
contains one of the configured holder keywords. Prefixes come from RIPEstat
announced-prefixes (routes seen by RIS in the last two weeks).
"""
from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

from .config import ROOT, Config
from .prefixes import top_level
from .sources import HttpClient


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def verify_asn(http: HttpClient, asn: int, keywords: list[str], my_asns: set[int]) -> dict:
    ov = http.ripestat("as-overview", resource=f"AS{asn}")
    try:
        pdb = http.peeringdb_net(asn)
    except Exception as e:  # PeeringDB is optional evidence
        pdb = {"_error": str(e)}
    holder = (ov.get("holder") or "").upper()
    pdb_name = (pdb or {}).get("name") or ""
    kw_hit = [k for k in keywords if k in holder or k in pdb_name.upper()]
    rec = {
        "asn": asn,
        "holder": ov.get("holder"),
        "announced": bool(ov.get("announced")),
        "registered_my": asn in my_asns,
        "peeringdb_name": pdb_name or None,
        "peeringdb_aka": (pdb or {}).get("aka") or None,
        "keyword_match": kw_hit,
        "sources": [ov["_source_url"]] + ([pdb["_source_url"]] if pdb and "_source_url" in pdb else []),
    }
    rec["accepted"] = rec["registered_my"] and bool(kw_hit)
    return rec


def build_watchlist(cfg: Config, http: HttpClient, out: Path | None = None) -> dict:
    out = out or cfg.data_dir / "watchlist.json"
    crl = http.ripestat("country-resource-list", resource="MY")
    my_asns = {int(a) for a in crl["resources"]["asn"]}
    result = {
        "built_at": _now(),
        "country_resource_list": {"source": crl["_source_url"], "query_time": crl.get("query_time"),
                                  "my_asn_count": len(my_asns)},
        "networks": [],
    }
    with ThreadPoolExecutor(max_workers=4) as pool:
        for n in cfg.networks:
            recs = list(pool.map(lambda a: verify_asn(http, a, n.holder_keywords, my_asns), n.all_asns))
            for r, a in zip(recs, n.all_asns):
                r["role"] = "primary" if a == n.primary_asn else "sibling"
            accepted = [r for r in recs if r["accepted"]]
            prefixes: dict[str, set[int]] = {}
            for r in accepted:
                if not r["announced"]:
                    r["prefix_count"] = 0
                    continue
                ap = http.ripestat("announced-prefixes", resource=f"AS{r['asn']}")
                r["prefix_count"] = len(ap["prefixes"])
                r["sources"].append(ap["_source_url"])
                r["prefix_window"] = [ap.get("query_starttime"), ap.get("query_endtime")]
                for p in ap["prefixes"]:
                    prefixes.setdefault(p["prefix"], set()).add(r["asn"])
            result["networks"].append({
                "key": n.key,
                "name": n.name,
                "asns": recs,
                "expected_origins": sorted(r["asn"] for r in accepted),
                "prefixes": {p: sorted(o) for p, o in sorted(prefixes.items())},
                "covering": top_level(list(prefixes)),
            })
    result["request_count"] = http.calls
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=1), encoding="utf-8")
    write_verification_report(result, ROOT / "docs" / "VERIFICATION.md")
    return result


def write_verification_report(wl: dict, path: Path) -> None:
    lines = [
        "# Watch-list verification report",
        "",
        f"Generated by `python -m bgpwatch build-watchlist` on **{wl['built_at']}** from live sources.",
        "Nothing in this table is typed from memory: each row is what the APIs returned at build time.",
        "",
        f"* Malaysian ASN registry: RIPEstat `country-resource-list` (query time "
        f"{wl['country_resource_list']['query_time']}, {wl['country_resource_list']['my_asn_count']} ASNs registered to MY).",
        "* Holder: RIPEstat `as-overview`. Network name: PeeringDB `/api/net`.",
        "* Prefixes: RIPEstat `announced-prefixes` (routes seen by RIS collectors in the past 2 weeks).",
        "",
        "An ASN is **accepted** only if it is registered to MY *and* its holder or PeeringDB name "
        "matches the configured keywords.",
        "",
        "| Network | ASN | Role | Registered holder (RIPEstat) | PeeringDB name | MY | Announced | Prefixes | Accepted |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for n in wl["networks"]:
        for a in n["asns"]:
            lines.append(
                f"| {n['key']} | AS{a['asn']} | {a['role']} | {a['holder'] or '-'} | {a['peeringdb_name'] or '-'} | "
                f"{'yes' if a['registered_my'] else 'NO'} | {'yes' if a['announced'] else 'no'} | "
                f"{a.get('prefix_count', '-')} | {'yes' if a['accepted'] else '**rejected**'} |")
    lines += ["", "## Totals", "", "| Network | Expected origins | Prefixes watched | Covering prefixes subscribed |",
              "|---|---|---|---|"]
    for n in wl["networks"]:
        lines.append(f"| {n['name']} | {', '.join('AS%d' % a for a in n['expected_origins'])} | "
                     f"{len(n['prefixes'])} | {len(n['covering'])} |")
    lines += ["", f"Network requests made for this build: {wl['request_count']}. Any other response was served from the "
              "local cache (`data/cache`), which holds API responses for at most `cache_ttl_h` hours (12 by default), "
              "so every row reflects the sources as they were within that window before the build time above.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def load_watchlist(cfg: Config, path: Path | None = None) -> dict:
    p = path or cfg.data_dir / "watchlist.json"
    return json.loads(p.read_text(encoding="utf-8"))
