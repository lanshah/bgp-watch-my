"""Write a Markdown summary of a monitoring database (what a live run actually saw)."""
from __future__ import annotations

import json
from collections import Counter
from datetime import datetime, timedelta, timezone
from pathlib import Path

from .store import Store

MYT = timezone(timedelta(hours=8))


def _t(ts) -> str:
    if not ts:
        return "-"
    return datetime.fromtimestamp(float(ts), MYT).strftime("%Y-%m-%d %H:%M MYT")


def live_report(store: Store, title: str = "Live run report") -> str:
    m = store.meta()
    c = m.get("counts", {})
    e = m.get("engine", {})
    ls = m.get("live_stats", {}) or {}
    started, stopped = m.get("started_at"), m.get("stopped_at") or m.get("event_time")
    rr = m.get("replay_result")
    if m.get("mode") != "live" and rr and rr.get("first_ts"):  # replays: use the recorded time span
        started, stopped = rr["first_ts"], rr["last_ts"]
    mins = (float(stopped) - float(started)) / 60 if started and stopped else 0
    sp = store.query("SELECT MIN(ts) a, MAX(ts) b FROM updates")[0]
    span = (sp["a"], sp["b"])
    span_min = (sp["b"] - sp["a"]) / 60 if sp["a"] else 0
    incs = store.query("SELECT id, kind, network, severity, status, first_seen, resolved_at, actor_asn, peers, "
                       "prefixes, summary FROM incidents ORDER BY first_seen")
    notes = store.query("SELECT COUNT(*) n FROM notifications WHERE channel='dashboard'")[0]["n"]
    quiet = store.query("SELECT COUNT(*) n FROM incidents i WHERE NOT EXISTS (SELECT 1 FROM notifications n "
                        "WHERE n.incident_id = i.id AND n.channel = 'dashboard')")[0]["n"]
    upd = store.query("SELECT network, COUNT(*) n, SUM(kind='A') a, SUM(kind='W') w FROM updates GROUP BY network")
    vis = store.query("SELECT network, COUNT(*) n, AVG(ratio) avg, MIN(ratio) min, SUM(ratio < 0.6) degraded "
                      "FROM prefix_state WHERE baseline > 0 GROUP BY network")
    rp = m.get("rpki_checks", {})
    lines = [f"# {title}", "",
             "Generated by `python -m bgpwatch report` from the monitoring database. Every number below was "
             "measured by the tool; nothing is estimated.", "",
             "## Run", "",
             f"* Mode: **{m.get('mode')}**. Started {_t(started)}, process ran {mins:.0f} min.",
             f"* BGP data actually received: {_t(span[0])} to {_t(span[1])} (**{span_min:.1f} min**). If this is much "
             "shorter than the process time, the PC was asleep or offline for the rest.",
             f"* Baseline built {m.get('baseline_built')} from RIPEstat RIS snapshot {m.get('ris_snapshot_times')}.",
             f"* RPKI VRP set: {(m.get('rpki') or {}).get('global_vrps', '-')} VRPs built "
             f"{(m.get('rpki') or {}).get('buildtime', '-')} ({(m.get('rpki') or {}).get('source', '-')}).",
             f"* Connection: {ls.get('connects', '-')} connect(s), {ls.get('disconnects', '-')} disconnect(s), "
             f"{float(ls.get('gaps_s', 0) or 0):.1f} s total gap; {ls.get('duplicates', 0)} duplicate deliveries dropped, "
             f"{ls.get('bad_messages', 0)} malformed frames, {ls.get('callback_errors', 0)} processing errors.",
             f"* PC clock vs RIS timestamps: {float(m.get('clock_offset_s') or 0):+.1f} s (corrected for).", "",
             "## Traffic", "",
             f"* RIS Live messages processed: **{c.get('messages', 0):,}** "
             f"({c.get('announcements', 0):,} prefix announcements, {c.get('withdrawals', 0):,} withdrawals; "
             f"{c.get('peer_down', 0)} RIS peer-down events; {c.get('bad_message', 0)} malformed messages skipped).",
             f"* RPKI checks on announcements: valid {rp.get('valid', 0):,}, not-found {rp.get('not-found', 0):,}, "
             f"invalid {rp.get('invalid', 0):,}.", "",
             "| Network | Updates stored | Announcements | Withdrawals | Prefixes with baseline | Avg visibility | Lowest | Degraded (< 60 %) |",
             "|---|---|---|---|---|---|---|---|"]
    vmap = {v["network"]: v for v in vis}
    for u in upd:
        v = vmap.get(u["network"], {})
        lines.append(f"| {u['network']} | {u['n']:,} | {u['a']:,} | {u['w']:,} | {v.get('n', '-')} | "
                     f"{(v.get('avg') or 0) * 100:.1f} % | {(v.get('min') or 0) * 100:.0f} % | {v.get('degraded', 0)} |")
    by = Counter((i["kind"], i["severity"]) for i in incs)
    lines += ["", "## Detections", "",
              f"* Raw findings: {e.get('findings', 0)} → incidents opened: **{e.get('incidents_opened', 0)}** "
              f"(reopened silently {e.get('incidents_reopened', 0)}) → notifications: **{notes}**.",
              f"* Findings folded into existing incidents: {e.get('dedup_suppressed', 0)}; incidents recorded "
              f"on the dashboard without a notification (below the paging threshold): {quiet}.", ""]
    if by:
        lines += ["| Incident kind | Severity | Count |", "|---|---|---|"]
        lines += [f"| {k} | {s} | {n} |" for (k, s), n in sorted(by.items())]
        lines += ["", "| # | First seen | Network | Kind | Severity | Status | Peers | Summary |", "|---|---|---|---|---|---|---|---|"]
        for i in incs[:60]:
            lines.append(f"| {i['id']} | {_t(i['first_seen'])} | {i['network']} | {i['kind']} | {i['severity']} | "
                         f"{i['status']} | {i['peers']} | {i['summary']} |")
    else:
        lines.append("No incidents were raised.")
    cs, ce = m.get("crosscheck_start"), m.get("crosscheck_end")
    if cs or ce:
        lines += ["", "## Outside check: our per-peer RIB vs RIPEstat looking-glass", "",
                  "RIPEstat `looking-glass` shows the route every RIS peer holds right now. For a fixed random sample of "
                  "watched prefixes, BGP Watch's per-peer table was compared with it before streaming started (accuracy "
                  "of the RIPEstat `bgp-state` seed, which is a few hours old) and again at the end (after live updates).",
                  "", "| Check | Prefixes | Identical peer sets | Within 2 peers / 2 % | AS-path agreement (common peers) | "
                  "Peer routes only in ours | Only in RIPEstat | Looking-glass data time (UTC) |",
                  "|---|---|---|---|---|---|---|---|"]
        for label, cc in (("Before streaming (seed)", cs), ("After the live run", ce)):
            if cc:
                lines.append(f"| {label} | {cc['prefixes']} | {cc['identical_pct']} % | {cc['close_pct']} % | "
                             f"{cc['path_agreement_pct']} % | {cc['only_ours']} | {cc['only_theirs']} | "
                             f"{' to '.join(cc['lg_time_range'])} |")
        if ce and ce.get("largest_differences"):
            lines += ["", "Largest differences at the end (prefix, peers ours / RIPEstat, peer-set difference, "
                      "path mismatches):", ""]
            lines += [f"* `{d[0]}`: {d[1]} / {d[2]}, diff {d[3]}, path mismatches {d[4]}" for d in ce["largest_differences"]]
    return "\n".join(lines) + "\n"


def write_report(store: Store, out: Path, title: str) -> None:
    out.write_text(live_report(store, title), encoding="utf-8")
